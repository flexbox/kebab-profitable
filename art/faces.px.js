/** Skin directly under hair, a hat or glasses falls into their shadow. */
function castShadow(above, onto = "HI", into = "Y") {
  return (c) => {
    const hit = []
    for (let y = 1; y < c.h; y++) {
      for (let x = 0; x < c.w; x++) {
        if (c.is(x, y, onto) && c.is(x, y - 1, above)) hit.push([x, y])
      }
    }
    for (const [x, y] of hit) c.px(x, y, into)
  }
}

/**
 * A finished face on its ground. `under` goes between the bare head and the
 * features (a beard), `over` on top of everything (hair, hats, glasses).
 * `flip` turns the head to the left instead.
 */
function face(name, { look, ground, eyes = "open", brows = "level", mouth = "smile", under = [], over = [], flip = false, shadow = "KLZ" }) {
  pal(look)
  figure(
    `_${name}_cut`,
    { w: 32, h: 32 },
    look.k,
    FACE,
    ...under,
    ...BROWS[brows],
    ...EYES[eyes],
    ...MOUTHS[mouth],
    ...over,
    castShadow(shadow),
  )
  sprite(name, { w: 32, h: 32 }, ...ground, stamp(`_${name}_cut`, -1, -1, flip ? { flip: "x" } : {}))
}

/** A ground that goes from one tone on the left to another on the right, in dithered bands. */
function fadeAcross(left, right, steps = 4) {
  return (c) => {
    for (let i = 0; i < steps; i++) {
      const x0 = Math.round((i * 32) / steps)
      const x1 = Math.round(((i + 1) * 32) / steps)
      const tone = hex(mix(rgb(left), rgb(right), i / (steps - 1)))
      c.rect(x0, 0, x1 - x0, 32, tone)
      if (i > 0) for (let y = 0; y < 32; y++) if (dithered(x0 - 1, y, 0.5)) c.px(x0 - 1, y, tone)
    }
  }
}

/** A ground that goes from one tone at the top to another at the bottom, in dithered bands. */
function fade(top, bottom, steps = 4) {
  return (c) => {
    for (let i = 0; i < steps; i++) {
      const y0 = Math.round((i * 32) / steps)
      const y1 = Math.round(((i + 1) * 32) / steps)
      const tone = hex(mix(rgb(top), rgb(bottom), i / (steps - 1)))
      c.rect(0, y0, 32, y1 - y0, tone)
      if (i > 0) for (let x = 0; x < 32; x++) if (dithered(x, y0 - 1, 0.5)) c.px(x, y0 - 1, tone)
    }
  }
}

